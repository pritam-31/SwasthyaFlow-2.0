/** A single exported row — the documented, fixed field set. No PII. */
interface ExportRow {
  sequenceNumber: number
  createdAt: string
  actorRole: string
  action: string
  category: string
  sessionId: string
  detail: string
  hash: string
  previousHash: string
  hashAlgorithm: string
  chainId: string
}

function sanitiseEntry(entry: AuditChainEntry): ExportRow {
  return {
    sequenceNumber: entry.sequenceNumber,
    createdAt: entry.at,
    actorRole: entry.role,
    action: entry.action,
    category: entry.category,
    sessionId: entry.sessionId,
    detail: enforceNonDiagnostic(anonymiseText(entry.detail, 'audit-detail').text),
    hash: entry.hash,
    previousHash: entry.previousHash,
    hashAlgorithm: entry.hashAlgorithm,
    chainId: entry.chainId,
  }
}

/** In-process registry of export refs → their format (survives the request). */
const exportRegistry = new Map<string, AuditExportFormat>()

/** Records an export's format so the download route can set the right headers. */
export function registerExportMeta(ref: string, format: AuditExportFormat): void {
  exportRegistry.set(ref, format)
}

export function exportFormatOf(ref: string): AuditExportFormat | undefined {
  return exportRegistry.get(ref)
}

const CSV_COLUMNS: Array<keyof ExportRow> = [
  'sequenceNumber',
  'createdAt',
  'actorRole',
  'action',
  'category',
  'sessionId',
  'detail',
  'hash',
  'previousHash',
]

function csvCell(value: string | number): string {
  const text = String(value)
  return /[",\n\r]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text
}

export function buildCsv(rows: ExportRow[]): Buffer {
  const lines = [CSV_COLUMNS.join(',')]
  for (const row of rows) {
    lines.push(CSV_COLUMNS.map((column) => csvCell(row[column])).join(','))
  }
  return Buffer.from(lines.join('\r\n'), 'utf8')
}

export function buildJson(rows: ExportRow[]): Buffer {
  return Buffer.from(JSON.stringify(rows, null, 2), 'utf8')
}

function wrap(text: string, font: { widthOfTextAtSize: (t: string, s: number) => number }, size: number, maxWidth: number): string[] {
  const words = text.split(/\s+/).filter(Boolean)
  const lines: string[] = []
  let current = ''
  for (const word of words) {
    const candidate = current ? `${current} ${word}` : word
    if (font.widthOfTextAtSize(candidate, size) > maxWidth && current) {
      lines.push(current)
      current = word
    } else {
      current = candidate
    }
  }
  if (current) lines.push(current)
  return lines.length > 0 ? lines : ['']
}

/**
 * Human-readable PDF report: header, filter summary, chain verification summary,
 * a fixed column table, per-page footer ("Page X to Y") and the disclaimer.
 */
export async function buildPdf(
  rows: ExportRow[],
  filter: AuditFilter,
  chainVerification: ChainVerificationResult,
  actor: AuditExportActor,
  language: SupportedLanguage,
): Promise<Buffer> {
  const labels = LABELS[language]
  const doc = await PDFDocument.create()
  const font = await doc.embedFont(StandardFonts.Helvetica)

  const pageWidth = 842
  const pageHeight = 595
  const margin = 32
  const fontSize = 9
  const lineHeight = 12

  let page = doc.addPage([pageWidth, pageHeight])
  let y = pageHeight - margin

  const newPage = (): void => {
    page = doc.addPage([pageWidth, pageHeight])
    y = pageHeight - margin
  }

  const write = (text: string, size = fontSize, color = rgb(0.12, 0.14, 0.18), indent = margin): void => {
    if (y < margin + 24) newPage()
    page.drawText(winAnsiSafe(text), { x: indent, y, size, font, color })
    y -= lineHeight
  }

  write(labels.title, 16, rgb(0.05, 0.1, 0.2))
  write(`${labels.generatedBy}: ${actor.name} (${actor.role}) · ${labels.notClinical}`, 9, rgb(0.35, 0.38, 0.45))
  y -= 4

  write(`${labels.filterSummary}:`, 11, rgb(0.05, 0.1, 0.2))
  write(`  ${labels.facility}: ${filter.facilityId}`)
  write(`  ${labels.window}: ${filter.since ?? '—'} → ${filter.until ?? '—'}`)
  write(`  ${labels.actions}: ${filter.actions?.join(', ') || labels.none}`)
  write(`  ${labels.categories}: ${filter.categories?.join(', ') || labels.none}`)
  write(`  ${labels.search}: ${filter.search || labels.none}`)
  y -= 4

  write(`${labels.chainSummary}:`, 11, rgb(0.05, 0.1, 0.2))
  const chainLine = chainVerification.valid ? labels.chainValid : labels.chainInvalid
  write(`  ${chainLine}`, 9, chainVerification.valid ? rgb(0.06, 0.5, 0.3) : rgb(0.75, 0.15, 0.15))
  write(`  ${labels.entriesChecked}: ${chainVerification.checkedEntries}`)
  if (!chainVerification.valid && chainVerification.firstInvalidSequence !== undefined) {
    write(`  ${labels.firstInvalid}: ${chainVerification.firstInvalidSequence}`)
  }
  y -= 6

  const columns: Array<{ key: keyof ExportRow; x: number; width: number; label: string }> = [
    { key: 'sequenceNumber', x: margin, width: 40, label: '#' },
    { key: 'createdAt', x: margin + 42, width: 110, label: 'createdAt' },
    { key: 'actorRole', x: margin + 154, width: 70, label: 'actorRole' },
    { key: 'action', x: margin + 226, width: 150, label: 'action' },
    { key: 'category', x: margin + 378, width: 70, label: 'category' },
    { key: 'sessionId', x: margin + 450, width: 100, label: 'sessionId' },
    { key: 'detail', x: margin + 552, width: 250, label: 'detail' },
  ]

  const drawHeaderRow = (): void => {
    if (y < margin + 24) newPage()
    for (const column of columns) {
      page.drawText(winAnsiSafe(column.label), { x: column.x, y, size: 8, font, color: rgb(0.3, 0.33, 0.4) })
    }
    y -= lineHeight
  }

  drawHeaderRow()

  for (const row of rows) {
    const detailLines = wrap(winAnsiSafe(row.detail), font, 8, columns[6].width)
    const rowHeight = Math.max(1, detailLines.length) * lineHeight
    if (y - rowHeight < margin + 20) {
      newPage()
      drawHeaderRow()
    }
    for (const column of columns.slice(0, 6)) {
      const raw = String(row[column.key])
      let text = raw
      while (font.widthOfTextAtSize(text, 8) > column.width && text.length > 1) {
        text = text.slice(0, -1)
      }
      page.drawText(winAnsiSafe(text), { x: column.x, y, size: 8, font, color: rgb(0.15, 0.17, 0.22) })
    }
    detailLines.forEach((line, index) => {
      page.drawText(winAnsiSafe(line), { x: columns[6].x, y: y - index * lineHeight, size: 8, font, color: rgb(0.15, 0.17, 0.22) })
    })
    y -= rowHeight
  }

  y -= 10
  if (y < margin + 40) newPage()
  for (const line of wrap(winAnsiSafe(labels.disclaimer), font, 8, pageWidth - margin * 2)) {
    write(line, 8, rgb(0.45, 0.2, 0.2))
  }

  const pages = doc.getPages()
  pages.forEach((p, index) => {
    const text = `${labels.page} ${index + 1} ${labels.of} ${pages.length}`
    p.drawText(winAnsiSafe(text), { x: pageWidth - margin - 80, y: 16, size: 8, font, color: rgb(0.45, 0.48, 0.55) })
    p.drawText(winAnsiSafe(labels.notClinical), { x: margin, y: 16, size: 8, font, color: rgb(0.45, 0.48, 0.55) })
  })

  const bytes = await doc.save()
  return Buffer.from(bytes)
}

/**
 * Standard PDF fonts (WinAnsi) cannot encode Devanagari/Odia glyphs, so any
 * non-Latin label or value would throw. Replace unsupported code points with a
 * placeholder — CSV/JSON exports keep full UTF-8 for the same content.
 */
function winAnsiSafe(text: string): string {
  let out = ''
  for (const ch of text) {
    out += (ch.codePointAt(0) ?? 0) <= 0xff ? ch : '?'
  }
  return out
}

function validateFormat(format: string): asserts format is AuditExportFormat {
  if (format !== 'csv' && format !== 'json' && format !== 'pdf') {
    throw new HttpError(400, "format must be one of: csv, json, pdf")
  }
}

export async function exportAudit(
  filter: AuditFilter,
  format: AuditExportFormat,
  actor: AuditExportActor,
  language: SupportedLanguage = 'en',
): Promise<AuditExportResult> {
  validateFormat(format)
  if (!filter.facilityId) throw new HttpError(400, 'facilityId is required.')

  const entries = listAuditFiltered({ ...filter, limit: 1000, sort: 'asc' })
  const rows = entries.map(sanitiseEntry)
  const chainVerification: ChainVerificationResult = verifyAuditChain(filter.facilityId)

  let buffer: Buffer
  if (format === 'csv') buffer = buildCsv(rows)
  else if (format === 'json') buffer = buildJson(rows)
  else buffer = await buildPdf(rows, filter, chainVerification, actor, language)

  if (buffer.byteLength > AUDIT_EXPORT_MAX_BYTES) {
    throw new HttpError(413, 'Export too large; narrow the filter')
  }

  const ref = newExportImageId()
  saveStoredImage(ref, buffer, 'export')
  registerExportMeta(ref, format)

  addAudit({
    facilityId: filter.facilityId,
    sessionId: 'audit',
    actor: actor.name,
    role: actor.role,
    action: 'audit.exported',
    detail: `Audit export (${format}) — ${rows.length} entr${rows.length === 1 ? 'y' : 'ies'}, ${buffer.byteLength} bytes, chain ${chainVerification.valid ? 'valid' : 'invalid'}.`,
    category: 'export',
  })

  return {
    ref,
    sizeBytes: buffer.byteLength,
    mimeType: AUDIT_EXPORT_MIME[format],
    recordCount: rows.length,
    format,
    createdAt: new Date().toISOString(),
  }
}

/** The chain meta for an export header / route (no PII). */
export function chainMetaForExport(facilityId: string): ReturnType<typeof getChainMetaForFacility> {
  return getChainMetaForFacility(facilityId)
}

/**
 * Retention-aware audit export (P2-16).
 *
 * Formats: CSV, JSON, PDF. CSV/JSON/PDF content is re-anonymised and
 * non-diagnostic-checked one final time before it is written (defence in depth).
 * Files are stored through the existing export mechanism (category `export`,
 * zero-PII media, purged by the `export-files` retention rule).
 *
 * Why `pdf-lib` over `pdfkit`: it is dependency-light (no streaming natives),
 * pure TypeScript, works with the existing Buffer-based store and lets us build
 * then page-count the document so a "Page X of Y" footer is trivial.
 */

export interface AuditExportActor {
  name: string
  role: UserRole
}


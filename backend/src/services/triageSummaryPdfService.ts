function winAnsiSafe(text: string): string {
  let out = ''
  for (const ch of text) {
    out += (ch.codePointAt(0) ?? 0) <= 0xff ? ch : '?'
  }
  return out
}

function wrap(text: string, font: { widthOfTextAtSize: (t: string, s: number) => number }, size: number, maxWidth: number): string[] {
  const words = text.split(/\s+/).filter((word) => word.length > 0)
  const lines: string[] = []
  let current = ''
  for (const word of words) {
    const candidate = current ? `${current} ${word}` : word
    if (font.widthOfTextAtSize(candidate, size) > maxWidth && current) {
      lines.push(current)
      current = word
    } else {
      current = candidate
    }
  }
  if (current) lines.push(current)
  return lines.length > 0 ? lines : ['']
}

async function renderPdf(sessionId: string, actor: TriageSummaryActor, language: SupportedLanguage): Promise<Buffer> {
  const session = getSession(sessionId)
  if (!session) throw new HttpError(404, 'Session not found.')

  const labels = LABELS[language]
  const summary = buildCaseSummaryOnePager(session, { generatedBy: actor.name, language })
  const safe = (value: string): string => winAnsiSafe(enforceNonDiagnostic(value))

  const doc = await PDFDocument.create()
  const font = await doc.embedFont(StandardFonts.Helvetica)
  const bold = await doc.embedFont(StandardFonts.HelveticaBold)
  const pageWidth = 595
  const pageHeight = 842
  const margin = 48
  const lineHeight = 15
  let page = doc.addPage([pageWidth, pageHeight])
  let y = pageHeight - margin

  const newPage = (): void => {
    page = doc.addPage([pageWidth, pageHeight])
    y = pageHeight - margin
  }
  const write = (text: string, size = 10, useBold = false, color = rgb(0.12, 0.14, 0.18)): void => {
    if (y < margin + 24) newPage()
    page.drawText(safe(text), { x: margin, y, size, font: useBold ? bold : font, color })
    y -= lineHeight
  }
  const paragraph = (text: string, size = 10): void => {
    for (const line of wrap(safe(text), font, size, pageWidth - margin * 2)) write(line, size)
  }

  write(labels.title, 18, true, rgb(0.05, 0.1, 0.2))
  write(`${labels.generatedBy}: ${actor.name} (${actor.role}) · ${labels.notClinical}`, 9, false, rgb(0.4, 0.43, 0.5))
  y -= 4
  write(`${labels.patient}: ${session.patientId}`, 10)
  write(`${labels.facility}: ${session.facilityId}`, 10)
  write(`${labels.assigned}: ${summary.assignedTo ?? labels.none}`, 10)
  y -= 4

  write(`${labels.complaint}:`, 11, true, rgb(0.05, 0.1, 0.2))
  paragraph(summary.chiefComplaint || labels.none)
  y -= 4

  write(`${labels.timeline}:`, 11, true, rgb(0.05, 0.1, 0.2))
  paragraph(summary.timelineSummary || labels.none)
  y -= 4

  write(`${labels.urgency}:`, 11, true, rgb(0.05, 0.1, 0.2))
  if (summary.topUrgencyFlags.length === 0) write(`  ${labels.none}`)
  for (const flag of summary.topUrgencyFlags) write(`  [${flag.severity}] ${flag.label}`)
  y -= 4

  write(`${labels.missing}:`, 11, true, rgb(0.05, 0.1, 0.2))
  if (summary.topMissingInfo.length === 0) write(`  ${labels.none}`)
  for (const item of summary.topMissingInfo) write(`  ${item.label} — ${item.whyItMatters}`)
  y -= 4

  write(`${labels.priority}: ${summary.priorityBand} (${summary.aggregateConfidence.toFixed(2)} ${labels.confidence})`, 11, true, rgb(0.05, 0.1, 0.2))
  paragraph(summary.priorityRationale)
  y -= 6

  for (const line of wrap(safe(labels.disclaimer), font, 8, pageWidth - margin * 2)) {
    write(line, 8, false, rgb(0.45, 0.2, 0.2))
  }

  const pages = doc.getPages()
  pages.forEach((p, index) => {
    p.drawText(winAnsiSafe(`${labels.page} ${index + 1} ${labels.of} ${pages.length}`), {
      x: pageWidth - margin - 80,
      y: 16,
      size: 8,
      font,
      color: rgb(0.45, 0.48, 0.55),
    })
    p.drawText(winAnsiSafe(labels.notClinical), { x: margin, y: 16, size: 8, font, color: rgb(0.45, 0.48, 0.55) })
  })

  return Buffer.from(await doc.save())
}

export async function buildTriageSummaryPdf(
  sessionId: string,
  actor: TriageSummaryActor,
  language?: SupportedLanguage,
): Promise<TriageSummaryPdf> {
  const session = getSession(sessionId)
  if (!session) throw new HttpError(404, 'Session not found.')
  const resolvedLanguage: SupportedLanguage = language ?? session.note?.language ?? 'en'

  const buffer = await renderPdf(sessionId, actor, resolvedLanguage)
  const ref = newExportImageId()
  saveStoredImage(ref, buffer, 'export', { sessionId })

  addAudit({
    sessionId,
    facilityId: session.facilityId,
    actor: actor.name,
    role: actor.role,
    action: 'session.summary-pdf',
    detail: `Triage summary PDF generated (${resolvedLanguage}, ${buffer.byteLength} bytes).`,
    category: 'export',
  })

  return {
    sessionId,
    ref,
    sizeBytes: buffer.byteLength,
    mimeType: 'application/pdf',
    generatedAt: new Date().toISOString(),
    generatedBy: actor.name,
    language: resolvedLanguage,
  }
}

export function getStoredTriageSummaryPdfBytes(ref: string, expectedSessionId?: string): Buffer | null {
  const stored = getStoredImage(ref)
  if (!stored || stored.category !== 'export') return null
  if (expectedSessionId && stored.sessionId !== expectedSessionId) return null
  return stored.buffer
}

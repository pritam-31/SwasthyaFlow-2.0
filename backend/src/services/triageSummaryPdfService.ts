/**
 * Triage summary PDF (P2-18 item O).
 *
 * A printable, non-diagnostic one-pager for a single case: chief complaint,
 * timeline, the top workflow urgency flags, the top missing-information checks,
 * the transparent priority band and the aggregate extraction confidence. It is
 * generated from already-anonymised, already-guarded note data, re-checked here
 * one final time, and stored under the short-lived `export` retention rule.
 */

